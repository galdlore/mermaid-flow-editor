export function formatCharList(chars: string[], lang: Language): string {
  return chars
    .map((ch) => {
      if (ch === ' ' || ch === '\t' || ch === '\n' || ch === '\r') {
        return lang === 'ja' ? '「空白」' : '"Space"';
      }
      return lang === 'ja' ? `「${ch}」` : `"${ch}"`;
    })
    .join(lang === 'ja' ? '' : ' ');
}
